_LOGGER = logging.getLogger(__name__)
SAVE_DELAY_SECONDS = 5
# An entire next hour must be complete and at least 15 minutes old before
# giving up on an earlier incomplete hour. ESPHome polls every five minutes.
RECOVERY_GRACE_SECONDS = 15 * 60
EVENT_STALE_SECONDS = 20 * 60


def supports_home_assistant_version(value: str) -> bool:
    """Require stable HA 2026.11.1 or newer, including manual installs."""
    match = re.match(r"^(\d{4})\.(\d{1,2})\.(\d+)(.*)$", value)
    if match is None:
        return False
    year, month, patch = map(int, match.groups()[:3])
    suffix = match.group(4)
    if suffix and (year, month) <= (2026, 11):
        return False
    return (year, month, patch) >= (2026, 11, 1)


async def async_setup_entry(hass: HomeAssistant, entry) -> bool:
    """Start a per-meter event listener and persistent import ledger."""
    from homeassistant import const as ha_const
    installed = getattr(ha_const, "__version__", None)
    if installed is not None and not supports_home_assistant_version(str(installed)):
        _LOGGER.error(
            "PalPulse 1.0.1b3 requires Home Assistant 2026.11.1 or later; found %s",
            installed,
        )
        return False
    meter = entry.data[CONF_METER_MAC]
    # Update only names generated by older PalPulse releases.
    # Keep user-customized titles, meter identity and all statistics untouched.
    if is_legacy_default_entry_title(getattr(entry, "title", None), meter):
        hass.config_entries.async_update_entry(entry, title=INTEGRATION_NAME)
    importer = PalPulseImporter(
        hass, meter, getattr(entry, "options", {}).get(CONF_ACK_SERVICE),
        ack_disabled=getattr(entry, "options", {}).get(CONF_DISABLE_ACK, False) is True,
    )
    await importer.async_load()
    # Cost tracking is opt-in. It cannot rewrite or interrupt energy history.
    from .cost import is_cost_enabled
    if is_cost_enabled(getattr(entry, "options", {})):
        from .cost_recorder import PalPulseCostRecorder
        cost_recorder = PalPulseCostRecorder(hass, entry, meter)
        await cost_recorder.async_load()
        cost_recorder.energy_importer = importer
        importer.cost_recorder = cost_recorder
        hass.data.setdefault(f"{DOMAIN}_cost", {})[entry.entry_id] = cost_recorder

    history_delivery = hass.data.setdefault(f"{DOMAIN}_history_delivery", {}).setdefault(
        entry.entry_id, {"received_count": 0, "last_event_at": None}
    )
    # ESPHome can emit recovered minutes before Recorder is fully available.
    # Buffer their original event payloads in order until HA has started.
    # A single entry-lifetime worker processes them sequentially so a large
    # replay doesn't spawn tracked startup tasks or hold up bootstrap.
    incoming: asyncio.Queue[dict] = asyncio.Queue()
    started = asyncio.Event()
    if hass.is_running:
        started.set()
    else:
        @callback
        def _on_started(_event: Event) -> None:
            started.set()

        entry.async_on_unload(
            hass.bus.async_listen_once(EVENT_HOMEASSISTANT_STARTED, _on_started)
        )

    async def _consume_events() -> None:
        await started.wait()
        while True:
            data = await incoming.get()
            try:
                await importer.async_receive(data)
            except Exception:
                # The importer journals its inputs and protects the cursor.
                # Never lose the entire event worker on an unexpected record.
                _LOGGER.exception(
                    "PalPulse incoming history worker failed for %s", meter
                )
            finally:
                incoming.task_done()

    async def _start_recovery() -> None:
        # No Recorder write or async_block_till_done during HA bootstrap.
        await started.wait()
        try:
            await importer.async_start()
        except Exception:
            _LOGGER.exception("PalPulse energy recovery could not start")

    async def _start_cost_recovery() -> None:
        # Cost recovery must not wait behind a long energy backlog. Each
        # writer has its own lock and retains its separate durable checkpoint.
        await started.wait()
        if cost_recorder := hass.data.get(f"{DOMAIN}_cost", {}).get(entry.entry_id):
            try:
                await cost_recorder.async_start()
            except Exception:
                _LOGGER.exception("PalPulse cost recovery could not start")

    # Config-entry background tasks do not block HA startup and are cancelled
    # on unload; this is critical because imports wait for durable Recorder
    # confirmation before advancing any meter/cost checkpoint.
    entry.async_create_background_task(
        hass, _start_recovery(), f"PalPulse deferred recovery {meter}",
        eager_start=False,
    )
    entry.async_create_background_task(
        hass, _consume_events(), f"PalPulse incoming minute events {meter}",
        eager_start=False,
    )
    entry.async_create_background_task(
        hass, _start_cost_recovery(), f"PalPulse independent cost recovery {meter}",
        eager_start=False,
    )

    @callback
    def _receive(event: Event) -> None:
        try:
            if normalize_mac(str(event.data.get("meter", ""))) != meter:
                return
        except (ValueError, TypeError, AttributeError):
            return
        history_delivery["received_count"] += 1
        history_delivery["last_event_at"] = int(time.time())
        incoming.put_nowait(dict(event.data))

    unsub = hass.bus.async_listen(EVENT_TYPE, _receive)
    entry.async_on_unload(unsub)
    hass.data.setdefault(DOMAIN, {})[entry.entry_id] = importer

    # An ESPHome checkpoint report is informational, keyed to this specific
    # Powerpal MAC. It never moves a firmware cursor or rewrites Recorder.
    try:
        from .panel_api import register_checkpoint_listener
        register_checkpoint_listener(hass, entry)
    except Exception:
        _LOGGER.exception("Unable to register PalPulse checkpoint telemetry")

    # Create one shared migration manager before either entity platform starts.
    # The progress sensors and buttons both observe the same live job.
    from .migration import LegacyMigration

    manager = LegacyMigration(hass, entry, importer.statistic_id)
    await manager.async_load()
    hass.data.setdefault(f"{DOMAIN}_migration", {})[entry.entry_id] = manager
    # Historical cost migration controls are always discoverable, independently
    # of pricing mode and whether a source is configured. Preview fails safely
    # with instructions if there is no source or live cost baseline.
    from .cost_migration import LegacyCostMigration
    cost_migration = LegacyCostMigration(
        hass, entry, f"{DOMAIN}:powerpal_{meter}_cost"
    )
    await cost_migration.async_load()
    hass.data.setdefault(f"{DOMAIN}_cost_migration", {})[
        entry.entry_id
    ] = cost_migration

    # Old versions displayed optional migration actions and completed-progress
    # sensors on the device page. Keep them working, but move them out of view
    # once, without changing user-named or already hidden entities.
    try:
        from .ui_cleanup import async_tidy_existing_entities
        await async_tidy_existing_entities(hass, entry, meter)
    except Exception:
        _LOGGER.exception("PalPulse optional entity-list cleanup failed")

    await hass.config_entries.async_forward_entry_setups(
        entry, [Platform.BUTTON, Platform.SENSOR]
    )
    # Pending energy and cost recovery is started by an entry-lifetime
    # background task after HA reaches its started state, not during setup.
    # Optional sidebar is isolated from metering. Failure must not interrupt
    # existing installations or historical migration safety.
    if getattr(hass, "http", None) is not None:
        try:
            from .panel import async_setup_panel
            await async_setup_panel(hass)
        except Exception:
            _LOGGER.exception("PalPulse sidebar could not load; metering remains active")
    return True


async def async_unload_entry(hass: HomeAssistant, entry) -> bool:
    """Avoid unloading a running migration or losing the active progress UI."""
    manager = hass.data.get(f"{DOMAIN}_migration", {}).get(entry.entry_id)
    cost_migration = hass.data.get(f"{DOMAIN}_cost_migration", {}).get(entry.entry_id)
    if cost_migration is not None and cost_migration.busy:
        _LOGGER.warning("PalPulse reload refused during an active cost migration")
        return False
    if manager is not None and manager.busy:
        _LOGGER.warning(
            "PalPulse integration reload refused while historical migration "
            "is active. Monitor migration progress before restarting Home Assistant"
        )
        return False
    if not await hass.config_entries.async_unload_platforms(
        entry, [Platform.BUTTON, Platform.SENSOR]
    ):
        return False
    hass.data.get(f"{DOMAIN}_migration", {}).pop(entry.entry_id, None)
    hass.data.get(f"{DOMAIN}_cost_migration", {}).pop(entry.entry_id, None)
    cost_recorder = hass.data.get(f"{DOMAIN}_cost", {}).pop(entry.entry_id, None)
    if cost_recorder:
        await cost_recorder.async_flush()
    importer = hass.data.get(DOMAIN, {}).pop(entry.entry_id, None)
    if importer:
        await importer.async_flush()

    hass.data.get(f"{DOMAIN}_checkpoint", {}).pop(entry.entry_id, None)
    hass.data.get(f"{DOMAIN}_checkpoint_delivery", {}).pop(entry.entry_id, None)
    hass.data.get(f"{DOMAIN}_history_delivery", {}).pop(entry.entry_id, None)
    hass.data.get(f"{DOMAIN}_replay_request", {}).pop(entry.entry_id, None)
    if getattr(hass, "http", None) is not None:
        try:
            from .panel import async_remove_panel_if_unused
            async_remove_panel_if_unused(hass)
        except Exception:
            _LOGGER.exception("PalPulse sidebar cleanup failed")
    return True


class PalPulseImporter:
    """Per-meter durable ledger and conservative hourly statistics importer."""

    def __init__(self, hass: HomeAssistant, mac: str, ack_service: str | None = None,
                 *, ack_disabled: bool = False) -> None:
        self.hass = hass
        self.mac = mac
        self._ack_service = ack_service
        self._ack_disabled = ack_disabled
        self._ack_timestamp: int | None = None
        self._ack_total: int | None = None
        self._ack_error: str | None = None
        self._device_rebase_deadline: int | None = None
        self._device_rebase_count = 0
        self.statistic_id = f"{DOMAIN}:powerpal_{mac}_energy"
        self._store = Store(hass, STORAGE_VERSION, f"{DOMAIN}_{mac}")
        self._lock = asyncio.Lock()
        self._records: dict[int, Record] = {}
        self._calibration: float | None = None
        self._baseline_pulses: int | None = None
        self._last_hour: int | None = None
        self._last_timestamp: int | None = None
        self._last_total: int | None = None
        self._halted = False
        self._accounted_pulses: int | None = None
        self._sum_offset = 0.0
        self._last_reconciled_at: int | None = None
        self._gap_count = 0
        self._repaired_gap_hours: set[int] = set()
        self._sparse_recovered_count = 0
        self._last_sparse_hour: int | None = None
        self._last_gap_hour: int | None = None
        self._blocked_hour: int | None = None
        self._last_event_at: int | None = None
        self._status_message = "Waiting for timestamped Powerpal records"
        self._last_import_error: str | None = None
        self._listeners: set = set()
        self._unsubscribe_retry = None

    def _snapshot(self) -> dict:
        return {
            "calibration": self._calibration,
            "baseline_pulses": self._baseline_pulses,
            "last_hour": self._last_hour,
            "last_timestamp": self._last_timestamp,
            "last_total": self._last_total,
            "halted": self._halted,
            "accounted_pulses": self._accounted_pulses,
            "sum_offset": self._sum_offset,
            "last_reconciled_at": self._last_reconciled_at,
            "gap_count": self._gap_count,
            "repaired_gap_hours": sorted(self._repaired_gap_hours),
            "sparse_recovered_count": self._sparse_recovered_count,
            "last_sparse_hour": self._last_sparse_hour,
            "last_gap_hour": self._last_gap_hour,
            "blocked_hour": self._blocked_hour,
            "last_event_at": self._last_event_at,
            "status_message": self._status_message,
            "last_import_error": self._last_import_error,
            "ack_timestamp": self._ack_timestamp,
            "ack_total": self._ack_total,
            "device_rebase_deadline": self._device_rebase_deadline,
            "device_rebase_count": self._device_rebase_count,
            "records": {
                str(t): [r.pulses, r.total_pulses]
                for t, r in self._records.items()
            },
        }

    async def async_load(self) -> None:
        state = await self._store.async_load() or {}
        self._calibration = state.get("calibration")
        self._baseline_pulses = state.get("baseline_pulses")
        self._last_hour = state.get("last_hour")
        self._last_timestamp = state.get("last_timestamp")
        self._last_total = state.get("last_total")
        self._halted = bool(state.get("halted", False))
        # Migration from the existing 0.1.0b7 live ledger. That version's
        # sum was (last_total - baseline) / calibration with no gaps skipped.
        if state.get("accounted_pulses") is not None:
            self._accounted_pulses = int(state["accounted_pulses"])
        elif self._last_total is not None and self._baseline_pulses is not None:
            self._accounted_pulses = int(self._last_total) - int(self._baseline_pulses)
        self._sum_offset = float(state.get("sum_offset", 0.0))
        self._last_reconciled_at = state.get("last_reconciled_at")
        if not math.isfinite(self._sum_offset):
            self._halted = True
            self._sum_offset = 0.0
            self._status_message = "Invalid saved Recorder sum offset; review required"
        self._gap_count = int(state.get("gap_count", 0))
        self._repaired_gap_hours = set(int(x) for x in state.get("repaired_gap_hours", []))
        self._sparse_recovered_count = int(state.get("sparse_recovered_count", 0))
        self._last_sparse_hour = state.get("last_sparse_hour")
        self._last_gap_hour = state.get("last_gap_hour")
        self._blocked_hour = state.get("blocked_hour")
        self._last_event_at = state.get("last_event_at")
        self._status_message = state.get("status_message", self._status_message)
        self._last_import_error = state.get("last_import_error")
        self._ack_timestamp = state.get("ack_timestamp")
        self._ack_total = state.get("ack_total")
        self._device_rebase_deadline = state.get("device_rebase_deadline")
        self._device_rebase_count = int(state.get("device_rebase_count", 0))
        if self._last_hour is not None and (
            self._accounted_pulses is None or self._accounted_pulses < 0
        ):
            self._halted = True
            self._status_message = "Invalid persisted energy cursor; manual review required"
        if self._calibration is not None:
            try:
                self._records = {
                    int(ts): Record(int(ts), int(vals[0]), int(vals[1]), float(self._calibration))
                    for ts, vals in state.get("records", {}).items()
                }
            except (ValueError, TypeError, IndexError):
                _LOGGER.error("Corrupt PalPulse pending measurement store; import paused")
                self._records = {}
                self._halted = True
        _LOGGER.info(
            "PalPulse importer for %s listening (statistics %s, last complete hour %s)",
            self.mac, self.statistic_id, self._last_hour,
        )

    def _resolved_ack(self) -> tuple[str | None, str]:
        return resolve_meter_ack(
            self.hass, self.mac, configured=self._ack_service,
            disabled=self._ack_disabled,
        )

    @property
    def health(self) -> dict:
        """Read-only live importer health, not legacy migration progress."""
        age = (int(time.time()) - self._last_event_at
               if self._last_event_at is not None else None)
        if self._halted:
            status = "Halted"
        elif self._last_import_error:
            status = "Recorder Error"
        elif age is None or age > EVENT_STALE_SECONDS:
            status = "No Events"
        elif self._blocked_hour is not None:
            status = "Waiting For Complete Hour"
        elif self._gap_count or self._sparse_recovered_count:
            status = "Active With Gaps"
        elif self._last_hour is None:
            status = "Collecting"
        else:
            status = "Active"
        ack_action, ack_status = self._resolved_ack()
        return {
            "status": status,
            "ack_enabled": not self._ack_disabled,
            "ack_resolution": ack_status,
            "last_event_received": self._last_event_at,
            "last_completed_utc_hour": self._last_hour,
            "blocked_utc_hour": self._blocked_hour,
            "skipped_hours": self._gap_count,
            "sparse_recovered_hours": self._sparse_recovered_count,
            "last_sparse_utc_hour": self._last_sparse_hour,
            "last_gap_utc_hour": self._last_gap_hour,
            "pending_minute_records": len(self._records),
            "message": self._status_message,
            "last_import_error": self._last_import_error,
            "ack_service": ack_action,
            "last_acknowledged_utc_minute": self._ack_timestamp,
            "ack_error": self._ack_error,
            "device_rebase_deadline": self._device_rebase_deadline,
            "device_rebase_count": self._device_rebase_count,
            "statistic_id": self.statistic_id,
            "sum_offset_kwh": self._sum_offset,
            "last_sum_reconciliation_utc_hour": self._last_reconciled_at,
        }

    def subscribe(self, callback):
        self._listeners.add(callback)
        return lambda: self._listeners.discard(callback)

    def _notify_health(self) -> None:
        for listener in tuple(self._listeners):
            listener()

    async def async_start(self) -> None:
        """Retry persisted energy hours after restarts or idle BLE periods."""
        from homeassistant.helpers.event import async_track_time_interval
        from datetime import timedelta

        if self._unsubscribe_retry is None:
            self._unsubscribe_retry = async_track_time_interval(
                self.hass, self._periodic_retry, timedelta(minutes=5),
            )
        await self.async_recover_pending()

    async def _periodic_retry(self, _now) -> None:
        await self.async_recover_pending()

    async def async_recover_pending(self) -> None:
        if self._halted or not self._records:
            return
        async with self._lock:
            if self._halted or not self._records or self._calibration is None:
                return
            now = int(time.time())
            try:
                await self._drain(now)
                self._last_import_error = None
            except Exception as err:
                self._last_import_error = f"{type(err).__name__}: {err}"
                _LOGGER.warning(
                    "PalPulse deferred energy recovery for %s: %s",
                    self.mac, self._last_import_error,
                )
            finally:
                self._prune(now)
                await self._store.async_save(self._snapshot())
                self._notify_health()

    async def async_arm_device_replacement(self) -> None:
        """One-time, 24h approval for an ESP32 checkpoint-reset transition.

        Only a later complete and counter-verified hour can establish the new
        raw state. The previous Recorder sum stays the sole continuity anchor.
        No data is written or deleted by arming.
        """
        async with self._lock:
            self._device_rebase_deadline = int(time.time()) + 86400
            self._halted = False
            self._status_message = (
                "ESP32 replacement armed for 24 hours. Awaiting a verified "
                "complete hour; unknown consumption will not be estimated"
            )
            await self._store.async_save(self._snapshot())
            self._notify_health()

    async def _ack_received(self, record: Record) -> None:
        """Confirm one durable minute, never an inferred or unverified event."""
        action, _ = self._resolved_ack()
        if action is None or self._halted or self._last_import_error:
            return
        if self._ack_timestamp is None:
            self._ack_timestamp = record.timestamp
            self._ack_total = record.total_pulses
        elif (
            record.timestamp > self._ack_timestamp
            and record.timestamp % RECORD_SECONDS == self._ack_timestamp % RECORD_SECONDS
            and record.total_pulses >= self._ack_total + record.pulses
        ):
            # The Powerpal buffer may have real missing native minutes. Once a
            # later event is durably journalled, ACK it even when timestamps
            # are not consecutive. The firmware only sends one event until
            # this exact ACK is accepted, so we never skip a queued event.
            self._ack_timestamp = record.timestamp
            self._ack_total = record.total_pulses
        # The recorder/pending ledger must reach storage before an ESP32 ACK.
        await self._store.async_save(self._snapshot())
        if self._ack_timestamp is None or record.timestamp > self._ack_timestamp:
            return
        domain, service = action.split(".", 1)
        if not self.hass.services.has_service(domain, service):
            self._ack_error = "ESPHome acknowledgment action not registered"
            return
        try:
            # Only acknowledge the exact event being retried, not an arbitrary
            # later cursor, because the firmware enforces strict queue order.
            await self.hass.services.async_call(
                domain, service, {"timestamp": record.timestamp}, blocking=True
            )
            self._ack_error = None
        except Exception as err:
            self._ack_error = f"{type(err).__name__}: {err}"
            _LOGGER.warning("PalPulse ESPHome ACK failed: %s", self._ack_error)

    async def async_receive(self, data: dict) -> None:
        now = int(time.time())
        record = parse_event(data, self.mac, now)
        if record is None:
            return
        async with self._lock:
            self._last_event_at = now
            self._notify_health()
            if self._halted:
                return
            if self._calibration is None:
                self._calibration = record.calibration
            elif self._calibration != record.calibration:
                self._halted = True
                self._status_message = "Calibration changed; live history halted"
                _LOGGER.error(
                    "PalPulse calibration changed for meter %s: %s to %s. "
                    "Importer halted to avoid invalid historical statistics",
                    self.mac, self._calibration, record.calibration,
                )
                await self._store.async_save(self._snapshot())
                return
            if record.timestamp in self._records:
                if not self._records[record.timestamp].same_measurement(record):
                    self._halted = True
                    self._status_message = "Conflicting record; live history halted"
                    _LOGGER.error(
                        "Conflicting Powerpal record at %s for meter %s; import halted",
                        record.timestamp, self.mac,
                    )
                    await self._store.async_save(self._snapshot())
                else:
                    await self._ack_received(record)
                return
            if (self._last_timestamp is not None and
                    record.timestamp <= self._last_timestamp):
                await self._ack_received(record)
                return  # Already imported, including duplicate replay after restart.
            self._records[record.timestamp] = record
            try:
                await self._drain(now)
                self._last_import_error = None
            except Exception as err:
                # Never advance the imported hour on Recorder exceptions.
                # A later event can retry idempotently from the saved cursor.
                message = f"{type(err).__name__}: {err}"
                if self._last_import_error != message:
                    _LOGGER.exception(
                        "PalPulse live Recorder write failed; keeping cursor "
                        "unchanged and retrying when new records arrive"
                    )
                self._last_import_error = message
                self._status_message = (
                    f"Recorder error; last imported hour unchanged: {message}"
                )
            finally:
                self._prune(now)
                if not self._ack_disabled and not self._halted and not self._last_import_error:
                    await self._ack_received(record)
                else:
                    self._store.async_delay_save(self._snapshot, SAVE_DELAY_SECONDS)
                self._notify_health()

    async def _recorder_hour(self, hour_start: int) -> list[dict]:
        """Read exact committed UTC hour; not an Energy chart aggregate."""
        start = datetime.fromtimestamp(hour_start, timezone.utc)
        end = datetime.fromtimestamp(hour_start + HOUR_SECONDS, timezone.utc)

        def read():
            return statistics_during_period(
                self.hass, start, end, {self.statistic_id},
                "hour", {"energy": "kWh"}, {"state", "sum"},
            ).get(self.statistic_id, [])

        return await get_instance(self.hass).async_add_executor_job(read)

    async def async_integrity_report(self, lookback_hours: int = 96) -> dict:
        """Read-only scan for discontinuities in recent energy statistics."""
        from .energy_integrity import detect_large_energy_resets

        end_stamp = (int(time.time()) // HOUR_SECONDS + 2) * HOUR_SECONDS
        start_stamp = end_stamp - max(24, min(168, lookback_hours)) * HOUR_SECONDS
        start = datetime.fromtimestamp(start_stamp, timezone.utc)
        end = datetime.fromtimestamp(end_stamp, timezone.utc)

        def read():
            return statistics_during_period(
                self.hass, start, end, {self.statistic_id},
                "hour", {"energy": "kWh"}, {"state", "sum"},
            ).get(self.statistic_id, [])

        rows = await get_instance(self.hass).async_add_executor_job(read)
        return {
            "statistic_id": self.statistic_id,
            "hour_count": len(rows),
            "issues": detect_large_energy_resets(rows),
            "last_completed_hour": self._last_hour,
            "offset": self._sum_offset,
        }

    async def _continuity_sum(self, hour) -> float:
        """Continue from the previous Recorder sum only if the meter state matches.

        Historic import can shift Recorder sums without modifying the Powerpal
        pulse cursor. We may adopt a sum offset only when the raw meter state
        agrees, and only for future hourly writes. Never rewrite old rows.
        """
        if self._last_hour is None or self._last_total is None:
            raise ValueError("Missing persisted energy hour")
        if self._calibration is None or self._accounted_pulses is None:
            raise ValueError("Missing meter calibration or accounted pulses")
        previous = await self._recorder_hour(self._last_hour)
        if len(previous) != 1 or int(previous[0]["start"]) != self._last_hour:
            raise ValueError(
                "Recorder last imported energy hour missing or ambiguous. "
                "Refusing an unsafe new cumulative energy baseline"
            )
        recorded_state = float(previous[0]["state"])
        recorded_sum = float(previous[0]["sum"])
        expected_state = self._last_total / self._calibration
        if not all(math.isfinite(x) for x in (recorded_state, recorded_sum)) or (
            not math.isclose(recorded_state, expected_state, rel_tol=0, abs_tol=1e-5)
        ):
            raise ValueError(
                "Recorder meter state does not match persisted Powerpal cursor; "
                "stopping energy writes instead of guessing a baseline"
            )
        delta = hour.consumption_pulses / self._calibration
        if not math.isfinite(delta) or delta < 0:
            raise ValueError("Invalid verified hour consumption")
        reconciled_offset = recorded_sum - self._accounted_pulses / self._calibration
        if not math.isclose(reconciled_offset, self._sum_offset, rel_tol=0, abs_tol=1e-5):
            _LOGGER.warning(
                "PalPulse Recorder energy sum was rebaselined for meter %s "
                "at UTC hour %s. Old offset=%s, verified Recorder offset=%s "
                "kWh. Future hour will follow the verified Recorder sum; "
                "no historical rows are modified",
                self.mac, self._last_hour, self._sum_offset, reconciled_offset,
            )
            self._sum_offset = reconciled_offset
            self._last_reconciled_at = self._last_hour
        new_sum = recorded_sum + delta
        if not math.isfinite(new_sum) or new_sum < recorded_sum:
            raise ValueError("Calculated next cumulative energy sum is invalid")
        return new_sum

    async def _verified_import(self, rows: list[dict]) -> None:
        """Never overwrite an existing different hourly statistic.

        Home Assistant's external-statistics API upserts matching timestamps.
        A prior crash can leave an already committed but unjournalled hour.
        Replaying identical rows is safe; conflicts must stop without a write.
        """
        pending = []
        for row in rows:
            stamp = int(row["start"].timestamp())
            stored = await self._recorder_hour(stamp)
            if stored:
                if len(stored) != 1 or int(stored[0]["start"]) != stamp or not (
                    math.isclose(float(stored[0]["state"]), row["state"],
                                 rel_tol=0, abs_tol=1e-5)
                    and math.isclose(float(stored[0]["sum"]), row["sum"],
                                     rel_tol=0, abs_tol=1e-5)
                ):
                    raise ValueError(
                        f"Existing Recorder energy at UTC {stamp} conflicts "
                        "with Powerpal cursor. Refusing overwrite"
                    )
            else:
                pending.append(row)
        if pending:
            await self._import(pending)
        for row in rows:
            stamp = int(row["start"].timestamp())
            saved = await self._recorder_hour(stamp)
            if len(saved) != 1 or int(saved[0]["start"]) != stamp or not (
                math.isclose(float(saved[0]["state"]), row["state"],
                             rel_tol=0, abs_tol=1e-5)
                and math.isclose(float(saved[0]["sum"]), row["sum"],
                                 rel_tol=0, abs_tol=1e-5)
            ):
                raise ValueError(
                    f"Recorder did not confirm expected energy hour UTC {stamp}; "
                    "cursor was not advanced"
                )

    async def _drain(self, now: int) -> None:
        """Import all complete hours, safely passing permanent missing hours.

        Never bridge a gap using an unadjusted meter total: its delta would
        misattribute missed energy to the first hour after the gap.
        """
        assert self._calibration is not None
        cutoff = ((now - 120) // HOUR_SECONDS) * HOUR_SECONDS
        candidates = sorted({(ts // HOUR_SECONDS) * HOUR_SECONDS
                             for ts in self._records})
        if self._last_hour is None:
            for start in candidates:
                if start + HOUR_SECONDS > cutoff:
                    continue
                hour = complete_hour(self._records, start)
                if (
                    hour is None
                    and now >= start + 2 * HOUR_SECONDS + RECOVERY_GRACE_SECONDS
                ):
                    hour = counter_verified_sparse_hour(self._records, start)
                if hour is None:
                    continue
                base = hour.first_total - hour.first_pulses
                if base < 0:
                    continue
                # Preserve the original first-hour zero baseline semantics.
                await self._verified_import([
                    {"start": datetime.fromtimestamp(start - HOUR_SECONDS, timezone.utc),
                     "state": base / self._calibration, "sum": 0.0},
                    self._statistic(hour, hour.consumption_pulses),
                ])
                if cost_recorder := getattr(self, "cost_recorder", None):
                    await cost_recorder.async_import_verified_hour(
                        hour, self._records, self._calibration
                    )
                self._baseline_pulses = base
                self._accounted_pulses = hour.consumption_pulses
                self._last_hour = start
                self._last_timestamp = hour.last_timestamp
                self._last_total = hour.last_total
                self._status_message = "First complete Powerpal hour imported"
                await self._store.async_save(self._snapshot())
                self._notify_health()
                _LOGGER.info("PalPulse first complete hour imported at %s UTC", start)
                break

        while self._last_hour is not None:
            start = self._last_hour + HOUR_SECONDS
            if start + HOUR_SECONDS > cutoff:
                return
            hour = complete_hour(self._records, start)
            # Give delayed BLE batches a full subsequent hour and recovery
            # grace before using cumulative endpoints instead of 60 minutes.
            if (
                hour is None
                and now >= start + 2 * HOUR_SECONDS + RECOVERY_GRACE_SECONDS
            ):
                hour = counter_verified_sparse_hour(self._records, start)
                if (
                    hour is None
                    and self._last_timestamp is not None
                    and self._last_total is not None
                ):
                    hour = counter_verified_from_previous(
                        self._records, start,
                        self._last_timestamp, self._last_total,
                    )
            skipped = 0
            if hour is None:
                # Wait for late five-minute BLE polls and buffered API events.
                # Only resume when a later complete hour is independently
                # verified and its end is at least 15 minutes in the past.
                for candidate in candidates:
                    if candidate <= start:
                        continue
                    if candidate + HOUR_SECONDS + RECOVERY_GRACE_SECONDS > now:
                        break
                    if candidate + HOUR_SECONDS > cutoff:
                        break
                    future = complete_hour(self._records, candidate)
                    if (
                        future is None
                        and now >= candidate + 2 * HOUR_SECONDS + RECOVERY_GRACE_SECONDS
                    ):
                        future = counter_verified_sparse_hour(
                            self._records, candidate
                        )
                    if future is not None:
                        hour = future
                        skipped = (candidate - start) // HOUR_SECONDS
                        break
                if hour is None:
                    if self._blocked_hour != start and any(
                        candidate > start for candidate in candidates
                    ):
                        self._blocked_hour = start
                        self._status_message = (
                            f"Incomplete UTC hour {start}; waiting for missing "
                            "records or a later complete hour"
                        )
                        _LOGGER.warning(
                            "PalPulse incomplete UTC hour %s: waiting for late "
                            "records or a verified recovery hour", start,
                        )
                        self._notify_health()
                    return

            if self._last_timestamp is None or self._last_total is None or (
                self._accounted_pulses is None
            ):
                self._halted = True
                self._status_message = "Missing persisted energy cursor; importer halted"
                await self._store.async_save(self._snapshot())
                self._notify_health()
                return

            first_before = hour.first_total - hour.first_pulses
            discontinuity = (
                first_before < self._last_total
                or (skipped == 0 and (
                    hour.first_timestamp != self._last_timestamp + RECORD_SECONDS
                    or hour.first_total != self._last_total + hour.first_pulses
                ))
            )
            permitted_device_rebase = (
                discontinuity
                and first_before < self._last_total
                and self._device_rebase_deadline is not None
                and now <= self._device_rebase_deadline
                and hour.missing_minutes == 0
            )
            if discontinuity and not permitted_device_rebase:
                self._halted = True
                self._status_message = (
                    f"Meter counter or timestamps discontinuous at UTC hour "
                    f"{hour.hour_start}; review required"
                )
                _LOGGER.error(
                    "PalPulse live import halted: meter discontinuity at UTC %s. "
                    "No energy was estimated or inserted", hour.hour_start
                )
                await self._store.async_save(self._snapshot())
                self._notify_health()
                return

            # Count only this hour's counter-verified energy.
            # Truly missing hours are never silently assigned to the next.
            next_accounted = self._accounted_pulses + hour.consumption_pulses
            recorder_sum = await self._continuity_sum(hour)
            await self._verified_import([
                self._statistic(hour, next_accounted, recorder_sum),
            ])
            # A sparse hour can still have an *exact* price when its entire
            # interval has one rate or one capped-free band. The writer
            # verifies this independently and refuses mixed tariffs.
            if cost_recorder := getattr(self, "cost_recorder", None):
                await cost_recorder.async_import_verified_hour(
                    hour, self._records, self._calibration
                )
            self._accounted_pulses = next_accounted
            if permitted_device_rebase:
                self._device_rebase_deadline = None
                self._device_rebase_count += 1
                _LOGGER.warning(
                    "PalPulse approved replacement ESP32 counter at UTC %s. "
                    "Previous unknown interval omitted; verified Recorder sum preserved",
                    hour.hour_start,
                )
            self._last_hour = hour.hour_start
            self._last_timestamp = hour.last_timestamp
            self._last_total = hour.last_total
            if permitted_device_rebase:
                self._status_message = (
                    f"ESP32 replacement accepted at UTC hour {hour.hour_start}; "
                    "old cumulative sum preserved without estimating missing interval"
                )
            if hour.missing_minutes:
                self._sparse_recovered_count += 1
                self._last_sparse_hour = hour.hour_start
                _LOGGER.warning(
                    "PalPulse recovered exact UTC hour %s with %d missing "
                    "interior minute(s); tariff cost withheld",
                    hour.hour_start, hour.missing_minutes,
                )
            if skipped:
                self._gap_count += skipped
                self._last_gap_hour = start
                self._status_message = (
                    f"Recovered after skipping {skipped} incomplete UTC hour(s), "
                    f"starting at {start}. Missing consumption was not estimated"
                )
                _LOGGER.warning(
                    "PalPulse recovered at UTC hour %s after %d skipped "
                    "hour(s) beginning %s; skipped energy not counted",
                    hour.hour_start, skipped, start,
                )
            elif hour.missing_minutes:
                self._status_message = (
                    f"Counter-verified UTC hour {hour.hour_start}; "
                    f"{hour.missing_minutes} missing minute(s); cost "
                    "recovery attempted only for uniform tariff bands"
                )
            elif not permitted_device_rebase:
                self._status_message = (
                    f"Imported complete UTC hour {hour.hour_start}"
                )
            self._blocked_hour = None
            await self._store.async_save(self._snapshot())
            self._notify_health()

    def _statistic(self, hour, accounted_pulses: int,
                   recorder_sum: float | None = None) -> dict:
        assert self._calibration is not None
        return {
            "start": datetime.fromtimestamp(hour.hour_start, timezone.utc),
            "state": hour.last_total / self._calibration,
            "sum": (accounted_pulses / self._calibration
                    if recorder_sum is None else recorder_sum),
        }

    async def _import(self, rows: list[dict]) -> None:
        metadata = {
            "statistic_id": self.statistic_id,
            "source": DOMAIN,
            "name": STAT_NAME,
            "unit_of_measurement": "kWh",
            "unit_class": "energy",
            "mean_type": StatisticMeanType.NONE,
            "has_sum": True,
        }
        # This queues Recorder work. Wait for its writes before advancing the
        # Store cursor, so an HA restart can't leave a committed cursor with
        # a missing corresponding statistic.
        async_add_external_statistics(self.hass, metadata, rows)
        await asyncio.wait_for(
            get_instance(self.hass).async_block_till_done(), timeout=180
        )

    def _prune(self, now: int) -> None:
        cutoff = now - MAX_BACKFILL_AGE
        if self._last_hour is not None:
            cutoff = max(cutoff, self._last_hour * 1 - HOUR_SECONDS)
        for stamp in list(self._records):
            if stamp < cutoff:
                del self._records[stamp]
        if len(self._records) > 12000:
            self._halted = True
            _LOGGER.error("PalPulse pending record ledger exceeded memory cap; halted")

    async def async_flush(self) -> None:
        if self._unsubscribe_retry is not None:
            self._unsubscribe_retry()
            self._unsubscribe_retry = None
        async with self._lock:
            await self._store.async_save(self._snapshot())
